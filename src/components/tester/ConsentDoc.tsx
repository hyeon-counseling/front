function Row({ k, v }: { k: string; v: React.ReactNode }) {
  return (
    <div className="border-t border-[var(--border-light)] py-3 first:border-t-0 sm:grid sm:grid-cols-[10rem_1fr] sm:gap-4">
      <dt className="text-sm font-semibold text-[var(--foreground)]">{k}</dt>
      <dd className="mt-1 text-sm leading-relaxed text-[var(--foreground-muted)] sm:mt-0">{v}</dd>
    </div>
  );
}

function Section({ title, children }: { title: string; children: React.ReactNode }) {
  return (
    <section className="card p-5 sm:p-6">
      <h2 className="text-lg font-bold text-[var(--foreground)]">{title}</h2>
      <div className="mt-3 space-y-3 text-[15px] leading-relaxed text-[var(--foreground-muted)]">{children}</div>
    </section>
  );
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="list-disc space-y-1.5 pl-5">
      {items.map((t) => (
        <li key={t}>{t}</li>
      ))}
    </ul>
  );
}

