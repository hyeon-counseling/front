/**
 * 종합심리검사 안내 문안 — 한 파일에 모은 데이터 (나중에 관리자 편집·DB로 옮기기 쉽게 JSX 없이 글과 구조만)
 *
 *   GUIDES       고정 안내 페이지 2개 × 탭 (/guide/apply · /guide/tests) — 알림톡 버튼이 탭 주소로 바로 연다
 *   DETAIL_FAQ   상품 상세(/assessment/comprehensive) '자주 묻는 질문' 8개
 *
 * 원본: 'hyeon test test/outputs-assessment' 카드뉴스 20·21(신청) · 25·22·23(검사). 10/30 웹으로 옮기며 운영 기준으로 다듬음.
 * 글 안의 [이름](/주소) 는 링크, **글** 은 굵게. 예시 문장은 모두 실제 검사 문항이 아니다.
 * 고치면 그 탭의 updated(마지막 수정일)를 함께 바꾼다 — 관리자 '안내·FAQ' 칸에 보인다.
 */

export type GuideBlock =
  | { type: "p"; text: string }
  | { type: "h3"; text: string }
  | { type: "steps"; items: { title: string; desc?: string; tag?: string }[] }
  | { type: "note"; title: string; text: string; tone?: "brand" | "coral" }
  | { type: "cards"; items: { title: string; text: string; badge?: string; sub?: string }[] }
  | { type: "list"; items: string[]; ordered?: boolean }
  | { type: "example"; text: string; answer?: string };

export interface GuideFaq {
  q: string;
  a: GuideBlock[];
}

export interface GuideSection {
  id: string;
  chip?: string;
  tone?: "coral" | "mmpi";
  title: string;
  blocks?: GuideBlock[];
  faq?: GuideFaq[];
}

export interface GuideTab {
  path: string; // 고정 주소 — 알림톡 버튼이 이 주소로 연다
  label: string; // 탭 이름
  title: string; // 관리자·문서 제목
  updated: string; // 마지막 수정일 YYYY-MM-DD
  source: string; // 원본 카드뉴스
  sections: GuideSection[];
}

export interface GuidePageData {
  key: "apply" | "tests";
  chip: string;
  title: string;
  lead: string;
  tabs: GuideTab[];
}

const p = (text: string): GuideBlock => ({ type: "p", text });
const h3 = (text: string): GuideBlock => ({ type: "h3", text });

